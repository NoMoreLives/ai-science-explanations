#!/usr/bin/env node
// Build site/scenes.js, the list the index page shows, from every scene's scene.json.
//   npm run index
// scene.json: { "title": "...", "desc": "...", "order": 10, "listed": true }
//   desc   one line for the index card, at most 120 characters
//   order  sort position on the index (gaps of 10 leave room to slot new scenes in)
//   listed false keeps a scene off the index (a draft); it still builds and plays at its own URL
// Every folder in site/ with an index.html (except engine/) needs a scene.json and, when listed, an icon.svg.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MAX_DESC = 120;
const site = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'site');
const errors = [];
const scenes = [];

for (const dir of fs.readdirSync(site).sort()) {
  if (dir === 'engine' || !fs.existsSync(path.join(site, dir, 'index.html'))) continue;
  const file = path.join(site, dir, 'scene.json');
  if (!fs.existsSync(file)) { errors.push(`${dir}: no scene.json`); continue; }
  let s;
  try { s = JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch (e) { errors.push(`${dir}/scene.json: ${e.message}`); continue; }
  if (typeof s.title !== 'string' || !s.title) errors.push(`${dir}: title missing`);
  if (typeof s.desc !== 'string' || !s.desc) errors.push(`${dir}: desc missing`);
  else if (s.desc.length > MAX_DESC) errors.push(`${dir}: desc is ${s.desc.length} characters, max ${MAX_DESC}`);
  if (typeof s.order !== 'number') errors.push(`${dir}: order must be a number`);
  if (typeof s.listed !== 'boolean') errors.push(`${dir}: listed must be true or false`);
  if (s.listed && !fs.existsSync(path.join(site, dir, 'icon.svg'))) errors.push(`${dir}: listed but has no icon.svg`);
  scenes.push({ dir, ...s });
}
if (errors.length) {
  for (const e of errors) console.error(`ERROR: ${e}`);
  process.exit(1);
}

const listed = scenes.filter(s => s.listed).sort((a, b) => a.order - b.order || a.dir.localeCompare(b.dir));
const out = `// Generated by scripts/build-index.mjs from each scene's scene.json: edit those, then run \`npm run index\`.
window.SCENES = [
${listed.map(s => '  ' + JSON.stringify({ path: `${s.dir}/`, title: s.title, desc: s.desc })).join(',\n')},
];
`;
fs.writeFileSync(path.join(site, 'scenes.js'), out);
const hidden = scenes.filter(s => !s.listed).map(s => s.dir);
console.log(`site/scenes.js: ${listed.length} scenes${hidden.length ? ` (not listed: ${hidden.join(', ')})` : ''}`);
